import AppKit
import TextToolCore
import UniformTypeIdentifiers

/// Watches the clipboard, keeps a short history, runs OCR on images, and writes conversions back.
@MainActor
final class ClipboardModel: ObservableObject {
    enum Source: Equatable {
        case empty
        case text
        case image(NSImage)
        case unsupported
    }

    /// One copied item. `text` is the original (copied text, or OCR result).
    struct Entry: Identifiable {
        let id = UUID()
        var text: String
        let image: NSImage?
        var selectedCase: TextCase?
    }

    static let historyLimit = 10

    @Published private(set) var source: Source = .empty
    /// The text conversions are applied to (copied text, or OCR result).
    @Published private(set) var original: String = ""
    /// What is shown in the preview and currently on the clipboard.
    @Published private(set) var current: String = ""
    @Published private(set) var selectedCase: TextCase?
    @Published private(set) var isRecognizing = false
    @Published private(set) var errorMessage: String?
    @Published private(set) var copiedFlash = false

    /// Recent items, newest first. Kept in memory only, never written to disk.
    @Published private(set) var history: [Entry] = []
    /// Index into `history` of the item shown, or nil while showing something not in history.
    @Published private(set) var historyIndex: Int?

    /// When true, OCR text replaces the copied image on the clipboard right away.
    @Published var autoReplaceImages: Bool {
        didSet { UserDefaults.standard.set(autoReplaceImages, forKey: Self.autoReplaceKey) }
    }

    private static let autoReplaceKey = "autoReplaceImages"
    /// Types password managers and similar apps set to ask clipboard tools not to record an item.
    private static let privateTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff, .init("public.jpeg"), .init("public.heic"),
    ]

    private let pasteboard = NSPasteboard.general
    /// Change count of the last clipboard state we have already processed (read or written).
    private var handledChangeCount = -1
    /// Change count last looked at by the background watcher.
    private var polledChangeCount = -1
    private var ocrTask: Task<Void, Never>?
    /// Bumped whenever new content arrives, so a stale OCR result is discarded.
    private var generation = 0
    private var flashTask: Task<Void, Never>?
    /// Typed edits are copied to the clipboard shortly after typing pauses.
    private var editCopyTask: Task<Void, Never>?
    private var hasPendingEditCopy = false
    private var watchTimer: Timer?

    init() {
        UserDefaults.standard.register(defaults: [Self.autoReplaceKey: true])
        autoReplaceImages = UserDefaults.standard.bool(forKey: Self.autoReplaceKey)
    }

    var hasText: Bool { !original.isEmpty }
    var canGoOlder: Bool { !isRecognizing && (historyIndex.map { $0 + 1 < history.count } ?? !history.isEmpty) }
    var canGoNewer: Bool { !isRecognizing && (historyIndex ?? 0) > 0 }

    // MARK: - Watching

    /// Records text copies in the background so history includes items copied while
    /// the popover was closed. Images are left alone until the popover is opened.
    func startWatching() {
        watchTimer?.invalidate()
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        watchTimer = timer
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != polledChangeCount else { return }
        polledChangeCount = count
        guard count != handledChangeCount, !Self.hasImage(pasteboard) else { return }
        refresh()
    }

    // MARK: - Reading

    /// Processes the clipboard if it changed since we last saw it (including our own writes).
    /// Called when the popover opens and by the background watcher.
    func refresh() {
        guard pasteboard.changeCount != handledChangeCount else { return }
        handledChangeCount = pasteboard.changeCount
        polledChangeCount = handledChangeCount

        let isPrivate = pasteboard.availableType(from: Self.privateTypes) != nil
        if let image = Self.readImage(from: pasteboard) {
            ingest(image: image, record: !isPrivate, copyResult: autoReplaceImages)
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            ingest(text: text, record: !isPrivate, copyResult: false)
        } else {
            resetPendingWork()
            source = pasteboard.pasteboardItems?.isEmpty == false ? .unsupported : .empty
            original = ""
            current = ""
            selectedCase = nil
            historyIndex = nil
        }
    }

    // MARK: - Paste & drop

    /// ⌘V in the popover: takes whatever is on the clipboard now as a new item,
    /// even if it was already seen (for example after browsing history).
    func pasteFromClipboard() {
        handledChangeCount = -1
        refresh()
    }

    /// Takes an image or text from a drag (e.g. dropped on the menu bar icon).
    /// The result is always copied to the clipboard. Returns false if nothing usable was found.
    @discardableResult
    func ingest(from dragPasteboard: NSPasteboard) -> Bool {
        if let image = Self.readImage(from: dragPasteboard) {
            ingest(image: image, record: true, copyResult: true)
        } else if let url = Self.fileURL(on: dragPasteboard) {
            return ingest(fileURL: url)
        } else if let text = dragPasteboard.string(forType: .string), !text.isEmpty {
            ingest(text: text, record: true, copyResult: true)
        } else {
            return false
        }
        return true
    }

    /// Takes the first image, image/text file, or text from SwiftUI drop providers.
    func ingest(providers: [NSItemProvider]) -> Bool {
        guard let provider = providers.first else { return false }
        if provider.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier) {
            _ = provider.loadObject(ofClass: URL.self) { [weak self] url, _ in
                guard let url else { return }
                Task { @MainActor in
                    if self?.ingest(fileURL: url) == false {
                        self?.errorMessage = "Drop an image or a text file."
                    }
                }
            }
            return true
        }
        if provider.canLoadObject(ofClass: NSImage.self) {
            _ = provider.loadObject(ofClass: NSImage.self) { [weak self] object, _ in
                guard let image = object as? NSImage else { return }
                Task { @MainActor in self?.ingest(image: image, record: true, copyResult: true) }
            }
            return true
        }
        if provider.canLoadObject(ofClass: String.self) {
            _ = provider.loadObject(ofClass: String.self) { [weak self] text, _ in
                guard let text, !text.isEmpty else { return }
                Task { @MainActor in self?.ingest(text: text, record: true, copyResult: true) }
            }
            return true
        }
        return false
    }

    /// Loads an image file (OCR) or a plain-text file. Returns false for other files.
    @discardableResult
    func ingest(fileURL url: URL) -> Bool {
        guard let type = UTType(filenameExtension: url.pathExtension) else { return false }
        if type.conforms(to: .image), let image = NSImage(contentsOf: url) {
            ingest(image: image, record: true, copyResult: true)
            return true
        }
        if type.conforms(to: .text), let text = try? String(contentsOf: url, encoding: .utf8), !text.isEmpty {
            ingest(text: text, record: true, copyResult: true)
            return true
        }
        return false
    }

    // MARK: - Ingesting

    private func resetPendingWork() {
        editCopyTask?.cancel()
        hasPendingEditCopy = false
        ocrTask?.cancel()
        generation += 1
        isRecognizing = false
        errorMessage = nil
    }

    private func ingest(text: String, record shouldRecord: Bool, copyResult: Bool) {
        resetPendingWork()
        if shouldRecord {
            record(Entry(text: text, image: nil))
        } else {
            show(text: text, image: nil, selectedCase: nil, index: nil)
        }
        if copyResult { copyToClipboard(text) }
    }

    private func ingest(image: NSImage, record shouldRecord: Bool, copyResult: Bool) {
        resetPendingWork()
        show(text: "", image: image, selectedCase: nil, index: nil)
        guard let cgImage = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else {
            errorMessage = "Couldn't read this image."
            return
        }
        isRecognizing = true
        let token = generation
        ocrTask = Task { [weak self] in
            do {
                let text = try await TextRecognizer.recognize(cgImage)
                guard let self, !Task.isCancelled, self.generation == token else { return }
                self.isRecognizing = false
                if shouldRecord {
                    self.record(Entry(text: text, image: image))
                } else {
                    self.show(text: text, image: image, selectedCase: nil, index: nil)
                }
                if copyResult { self.copyToClipboard(text) }
            } catch {
                guard let self, !Task.isCancelled, self.generation == token else { return }
                self.isRecognizing = false
                self.errorMessage = error.localizedDescription
            }
        }
    }

    // MARK: - Pasteboard helpers

    /// True if the pasteboard's primary content is an image: a screenshot, an image copied
    /// from a browser or Preview, or an image file copied in Finder.
    private static func hasImage(_ pasteboard: NSPasteboard) -> Bool {
        if let url = fileURL(on: pasteboard), UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true {
            return true
        }
        guard pasteboard.availableType(from: imageTypes) != nil else { return false }
        // Apps like Word/Pages put an image preview next to real text; prefer the text then.
        // A lone URL string (browsers' "Copy Image") still counts as an image copy.
        if let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
           !text.isEmpty, !looksLikeSingleURL(text) {
            return false
        }
        return true
    }

    private static func readImage(from pasteboard: NSPasteboard) -> NSImage? {
        guard hasImage(pasteboard) else { return nil }
        if let url = fileURL(on: pasteboard), UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true {
            return NSImage(contentsOf: url)
        }
        return NSImage(pasteboard: pasteboard)
    }

    private static func fileURL(on pasteboard: NSPasteboard) -> URL? {
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
        return urls?.first
    }

    private static func looksLikeSingleURL(_ text: String) -> Bool {
        guard !text.contains(where: \.isWhitespace), let url = URL(string: text) else { return false }
        return url.scheme != nil
    }

    // MARK: - History

    /// Adds an item as the newest history entry (moving it up if it was already there) and shows it.
    private func record(_ entry: Entry) {
        history.removeAll { $0.text == entry.text && ($0.image == nil) == (entry.image == nil) }
        history.insert(entry, at: 0)
        if history.count > Self.historyLimit { history.removeLast(history.count - Self.historyLimit) }
        show(text: entry.text, image: entry.image, selectedCase: nil, index: 0)
    }

    private func show(text: String, image: NSImage?, selectedCase: TextCase?, index: Int?) {
        source = image.map(Source.image) ?? (text.isEmpty ? .empty : .text)
        original = text
        self.selectedCase = selectedCase
        current = selectedCase.map { CaseConverter.convert(text, to: $0) } ?? text
        historyIndex = index
    }

    /// Shows an older history item and copies it to the clipboard.
    func showOlder() {
        guard canGoOlder else { return }
        go(to: historyIndex.map { $0 + 1 } ?? 0)
    }

    /// Shows a newer history item and copies it to the clipboard.
    func showNewer() {
        guard canGoNewer, let index = historyIndex else { return }
        go(to: index - 1)
    }

    private func go(to index: Int) {
        resetPendingWork()
        let entry = history[index]
        show(text: entry.text, image: entry.image, selectedCase: entry.selectedCase, index: index)
        copyToClipboard(current)
    }

    // MARK: - Actions

    func apply(_ textCase: TextCase) {
        guard hasText else { return }
        setCase(textCase)
    }

    /// Restores the original text (or OCR result) to the preview and clipboard.
    func restoreOriginal() {
        guard hasText else { return }
        setCase(nil)
    }

    // MARK: - Editing

    /// True when the preview shows editable text (not while recognizing, or with nothing loaded).
    var canEdit: Bool {
        guard !isRecognizing, errorMessage == nil else { return false }
        switch source {
        case .text, .image: return true
        case .empty, .unsupported: return false
        }
    }

    /// Called as the user types in the preview. The edited text becomes the new base for
    /// case conversions, replaces the item in history, and is copied once typing pauses.
    func edit(_ text: String) {
        guard text != current else { return }
        original = text
        current = text
        selectedCase = nil
        if let index = historyIndex {
            history[index].text = text
            history[index].selectedCase = nil
        }
        hasPendingEditCopy = true
        editCopyTask?.cancel()
        editCopyTask = Task { [weak self] in
            try? await Task.sleep(for: .milliseconds(500))
            guard !Task.isCancelled else { return }
            self?.flushPendingEdit()
        }
    }

    /// Copies a not-yet-copied edit right away (e.g. when the popover closes).
    func flushPendingEdit() {
        editCopyTask?.cancel()
        guard hasPendingEditCopy else { return }
        hasPendingEditCopy = false
        copyToClipboard(current)
    }

    private func setCase(_ textCase: TextCase?) {
        selectedCase = textCase
        current = textCase.map { CaseConverter.convert(original, to: $0) } ?? original
        if let index = historyIndex { history[index].selectedCase = textCase }
        copyToClipboard(current)
    }

    private func copyToClipboard(_ text: String) {
        editCopyTask?.cancel()
        hasPendingEditCopy = false
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        handledChangeCount = pasteboard.changeCount
        polledChangeCount = handledChangeCount

        copiedFlash = true
        flashTask?.cancel()
        flashTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(1.6))
            guard !Task.isCancelled else { return }
            self?.copiedFlash = false
        }
    }
}
